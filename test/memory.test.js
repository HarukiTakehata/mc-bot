'use strict'
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { createExperience, similarity } = require('../experience')
const { createContainers } = require('../containers')
const { normalizeAction } = require('../security')

const tmp = (name) => path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'mcmem-')), name)

test('相似目标能找回经验，不相关的不会', () => {
  const x = createExperience({ file: tmp('e.json') })
  x.record({ goal: '砍20个原木做箱子', outcome: 'done', rounds: 3, steps: ['chop 20', 'craft chest'] })
  x.record({ goal: '去下界挖远古残骸', outcome: 'failed', rounds: 9, why: ['goto（失败）'] })
  assert.match(x.recall('帮我砍原木')[0], /做成了.*chop 20/)
  assert.match(x.recall('挖远古残骸')[0], /没做成.*goto/)
  assert.deepEqual(x.recall('今天天气怎么样'), [])
  assert.ok(similarity('iron_ingot 24', 'get iron_ingot') > 0)
})
test('同一目标只留最新结果，重启后还在，可清空', () => {
  const file = tmp('e.json')
  const x = createExperience({ file })
  x.record({ goal: '挖铁', outcome: 'failed', rounds: 2 })
  x.record({ goal: '挖铁', outcome: 'done', rounds: 4 })
  const y = createExperience({ file })
  assert.equal(y.recent().length, 1)
  assert.match(y.recent()[0], /做成了/)
  y.clear()
  assert.deepEqual(createExperience({ file }).recent(), [])
})
test('坏数据和超量不会写坏文件', () => {
  const file = tmp('e.json')
  fs.writeFileSync(file, JSON.stringify({ entries: [null, { goal: 1 }, { goal: 'a', outcome: 'x' }] }))
  const x = createExperience({ file })
  assert.deepEqual(x.recent(), [])
  assert.equal(x.record({ goal: '', outcome: 'done' }), false)
  for (let i = 0; i < 80; i++) x.record({ goal: `目标${i}${'长'.repeat(80)}`, outcome: 'failed', rounds: 2, steps: Array(10).fill('步'.repeat(24)), why: Array(3).fill('因'.repeat(40)) })
  assert.ok(fs.statSync(file).size <= 32_768)
  assert.ok(createExperience({ file }).recent(50).length >= 1)
})
test('箱子记忆：近的在前，分维度，能重载', () => {
  const file = tmp('c.json')
  const c = createContainers({ file })
  const from = { x: 0, y: 64, z: 0 }
  c.update({ x: 50, y: 64, z: 0 }, 'overworld', [{ name: 'iron_ingot', count: 5 }])
  c.update({ x: 5, y: 64, z: 0 }, 'overworld', [{ name: 'iron_ingot', count: 3 }, { name: 'iron_ingot', count: 2 }, { name: 'dirt', count: 64 }])
  c.update({ x: 1, y: 64, z: 0 }, 'the_nether', [{ name: 'iron_ingot', count: 9 }])
  const hits = createContainers({ file }).find('iron_ingot', 'overworld', from)
  assert.deepEqual(hits.map((h) => [h.x, h.count]), [[5, 5], [50, 5]])
  assert.match(c.describe('overworld', from, '要 iron_ingot'), /^iron_ingotx10\(最近 5,64,0\)/)
})
test('箱子记忆：取空后不再报，大箱子不重复，方块没了能删', () => {
  const c = createContainers({ file: tmp('c.json') })
  const from = { x: 0, y: 0, z: 0 }
  c.update({ x: 1, y: 0, z: 0 }, 'o', [{ name: 'dirt', count: 4 }])
  c.update({ x: 2, y: 0, z: 0 }, 'o', [{ name: 'dirt', count: 4 }], { double: true })
  assert.equal(c.size(), 1)
  c.update({ x: 2, y: 0, z: 0 }, 'o', [])
  assert.deepEqual(c.find('dirt', 'o', from), [])
  c.drop({ x: 2, y: 0, z: 0 }, 'o')
  assert.equal(c.size(), 0)
})
test('箱子记忆：容量有上限，模型给的怪名字进不来', () => {
  const file = tmp('c.json')
  const c = createContainers({ file })
  for (let i = 0; i < 60; i++) c.update({ x: i * 3, y: 0, z: 0 }, 'o', Array.from({ length: 27 }, (_, k) => ({ name: `some_mod:item_number_${k}`, count: 1 })).concat({ name: 'A B', count: 1 }))
  assert.ok(c.size() <= 40)
  assert.ok(fs.statSync(file).size <= 32_768)
  assert.equal(c.find('A B', 'o', { x: 0, y: 0, z: 0 }).length, 0)
})
test('新指令的权限：AI 能取能查，不能清经验', () => {
  assert.deepEqual(normalizeAction('fetch', ['minecraft:iron_ingot', '3'], { ai: true }).args, ['iron_ingot', '3'])
  assert.deepEqual(normalizeAction('chestscan', [], { ai: true }).args, ['16'])
  assert.throws(() => normalizeAction('chestscan', ['99']))
  assert.deepEqual(normalizeAction('chests', ['dirt'], { ai: true }).args, ['dirt'])
  assert.throws(() => normalizeAction('lessons', ['clear'], { ai: true }))
  assert.deepEqual(normalizeAction('lessons', ['clear']).args, ['clear'])
})
